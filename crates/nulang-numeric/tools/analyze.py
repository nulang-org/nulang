#!/usr/bin/env python3
"""Analyze paired Rust numeric view/copy timings. Diagnostic, never a CI gate."""

import argparse
import csv
import json
import random
import statistics
import sys
from collections import defaultdict

COLUMNS = frozenset(
    {"size", "range_len", "iterations", "round", "mode", "elapsed_ns", "checksum"}
)


def analyze_csv(source):
    reader = csv.DictReader(source)
    if not reader.fieldnames or not COLUMNS.issubset(reader.fieldnames):
        raise ValueError("missing required CSV columns")

    samples = defaultdict(dict)
    for line, row in enumerate(reader, start=2):
        try:
            size = int(row["size"])
            length = int(row["range_len"])
            iterations = int(row["iterations"])
            round_id = int(row["round"])
            elapsed = int(row["elapsed_ns"])
            checksum = int(row["checksum"])
        except (ValueError, TypeError, KeyError) as exc:
            raise ValueError(f"invalid integer field on line {line}") from exc
        mode = row["mode"]
        if mode not in {"view", "copy"}:
            raise ValueError(f"invalid mode on line {line}")
        if elapsed <= 0:
            raise ValueError(f"elapsed_ns must be positive on line {line}")
        if not (0 <= length <= size and size > 0 and iterations > 0 and round_id >= 0):
            raise ValueError(f"invalid workload dimensions on line {line}")
        key = (size, length, iterations, round_id)
        if mode in samples[key]:
            raise ValueError(f"duplicate {mode} measurement in round {round_id}")
        samples[key][mode] = (elapsed, checksum)

    groups = defaultdict(list)
    for (size, length, iterations, round_id), modes in samples.items():
        if set(modes) != {"copy", "view"}:
            raise ValueError(f"incomplete view/copy pair in round {round_id}")
        if modes["copy"][1] != modes["view"][1]:
            raise ValueError(f"checksum mismatch in round {round_id}")
        groups[(size, length, iterations)].append(
            (round_id, modes["view"][0], modes["copy"][0])
        )

    workloads = []
    for (size, length, iterations), pairs in sorted(groups.items()):
        pairs.sort()
        if len(pairs) < 2:
            raise ValueError("each workload needs at least two paired rounds")
        ids = [p[0] for p in pairs]
        if len(ids) != len(set(ids)):
            raise ValueError("duplicate round in workload")
        view_times = [p[1] for p in pairs]
        copy_times = [p[2] for p in pairs]
        ratios = [v / c for v, c in zip(view_times, copy_times)]
        rng = random.Random(0)
        bootstraps = sorted(
            statistics.median(rng.choices(ratios, k=len(ratios))) for _ in range(2000)
        )
        workloads.append(
            {
                "size": size,
                "range_len": length,
                "iterations": iterations,
                "rounds": len(pairs),
                "median_view_ns": statistics.median(view_times),
                "median_copy_ns": statistics.median(copy_times),
                "paired_median_ratio": statistics.median(ratios),
                "bootstrap_95_ratio": [bootstraps[49], bootstraps[1949]],
            }
        )

    if not workloads:
        raise ValueError("no paired measurements")
    return {
        "interpretation": "Diagnostic native-Rust primitive timings, not evidence of Nulang VM speedup; shared CI hosts are noisy.",
        "workloads": workloads,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", help="CSV generated by compare_views, or - for stdin")
    args = parser.parse_args(argv)
    if args.csv == "-":
        results = analyze_csv(sys.stdin)
    else:
        with open(args.csv, encoding="utf-8", newline="") as source:
            results = analyze_csv(source)
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
