//! Deterministic local content ingestion. Only package tooling reads files;
//! compiled handlers receive ordinary string/record/array values, never a
//! filesystem capability. The snapshot is private to one web invocation.

use super::manifest::WebSection;
use serde::Deserialize;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Component, Path, PathBuf};

pub(super) const IMPORT: &str = "web_content";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct FrontMatter {
    slug: String,
    title: String,
    #[serde(default)]
    summary: String,
    #[serde(default)]
    tags: Vec<String>,
    #[serde(default)]
    draft: bool,
}

struct Entry {
    meta: FrontMatter,
    body: String,
    source: String,
}

/// The import is resolved by the existing package module-path mechanism.
/// Keep it alive for every compiler invocation (including deploy's native
/// and optional WASM compilation), so every artifact uses identical inputs.
pub(super) struct ContentSnapshot {
    directory: PathBuf,
    module_path: String,
}

impl ContentSnapshot {
    pub(super) fn new(root: &Path, web: &WebSection) -> Result<Option<Self>, String> {
        if web.content.is_empty() {
            return Ok(None);
        }
        let root = root.canonicalize().map_err(|err| err.to_string())?;
        let output = relative_path(&root, &web.output_dir)?;
        // Dev writes some artifacts directly, so it must not follow an output
        // alias into the content tree either.
        require_directory(&root, &output, true)?;
        let assets = root.join(&web.static_dir);
        // Resolve existing asset aliases too; a symlink must not make
        // unpublished content part of the public asset tree.
        let assets = assets.canonicalize().unwrap_or(assets);
        let mut source = String::from(
            "// Generated by nula web from validated Markdown.\n\
             pub type WebContentEntry = { slug: String, title: String, summary: String, tags: [String], body: String, source: String }\n",
        );
        let mut bundle_roots = Vec::<PathBuf>::new();
        for (name, directory) in &web.content {
            if name.is_empty()
                || !name.as_bytes()[0].is_ascii_lowercase()
                || !name
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
            {
                return Err(format!("invalid web content bundle name '{name}'"));
            }
            let directory = relative_path(&root, directory)?;
            for protected in [
                root.join(".git"),
                root.join(".nula"),
                output.clone(),
                assets.clone(),
            ] {
                if overlaps(&directory, &protected) {
                    return Err(format!(
                        "content bundle '{name}' overlaps protected path {}",
                        protected.display()
                    ));
                }
            }
            if bundle_roots
                .iter()
                .any(|previous| overlaps(previous, &directory))
            {
                return Err(format!("content bundle '{name}' overlaps another bundle"));
            }
            bundle_roots.push(directory.clone());
            require_directory(&root, &directory, false)?;
            let mut paths = Vec::new();
            collect_markdown(&directory, &mut paths)?;
            // OS directory iteration order and absolute root are not inputs
            // to generated values. Sort by portable source path.
            let mut entries = Vec::new();
            for path in paths {
                let origin = path
                    .strip_prefix(&root)
                    .expect("contained content path")
                    .components()
                    .map(|c| c.as_os_str().to_str())
                    .collect::<Option<Vec<_>>>()
                    .ok_or_else(|| format!("content path is not UTF-8: {}", path.display()))?
                    .join("/");
                entries.push(read_entry(&path, origin)?);
            }
            entries.sort_by(|a, b| a.source.cmp(&b.source));
            let mut slugs = BTreeSet::new();
            for entry in &entries {
                if !slugs.insert(entry.meta.slug.to_ascii_lowercase()) {
                    return Err(format!(
                        "{}: duplicate content slug '{}' in bundle '{name}'",
                        entry.source, entry.meta.slug
                    ));
                }
            }
            writeln!(source, "pub fn content_{name}() -> [WebContentEntry] {{ [").unwrap();
            for entry in entries.iter().filter(|entry| !entry.meta.draft) {
                let meta = &entry.meta;
                let tags = meta
                    .tags
                    .iter()
                    .map(|tag| quote(tag))
                    .collect::<Vec<_>>()
                    .join(", ");
                writeln!(
                    source,
                    "    {{slug: {}, title: {}, summary: {}, tags: [{}], body: {}, source: {}}},",
                    quote(&meta.slug),
                    quote(&meta.title),
                    quote(&meta.summary),
                    tags,
                    quote(&entry.body),
                    quote(&entry.source)
                )
                .unwrap();
            }
            source.push_str("] }\n");
        }

        let build_dir = root.join(".nula");
        match fs::symlink_metadata(&build_dir) {
            Ok(meta) if meta.is_dir() && !meta.file_type().is_symlink() => (),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                fs::create_dir(&build_dir).map_err(|err| err.to_string())?;
            }
            _ => {
                return Err(format!(
                    "content snapshot requires a real directory: {}",
                    build_dir.display()
                ))
            }
        }
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(|err| err.to_string())?
            .as_nanos();
        let directory = build_dir.join(format!("web-content-{}-{stamp}", std::process::id()));
        let path = directory
            .to_str()
            .filter(|path| !path.contains(';'))
            .ok_or("content snapshot path is not representable in NULANG_MODULE_PATH")?;
        let module_path = format!("@nulang/{IMPORT}={path}");
        fs::create_dir(&directory).map_err(|err| err.to_string())?;
        let snapshot = Self {
            directory,
            module_path,
        };
        fs::write(snapshot.directory.join("lib.nula"), source).map_err(|err| err.to_string())?;
        Ok(Some(snapshot))
    }

    pub(super) fn module_path(&self) -> &str {
        &self.module_path
    }
}

impl Drop for ContentSnapshot {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.directory);
    }
}

fn overlaps(a: &Path, b: &Path) -> bool {
    a.starts_with(b) || b.starts_with(a)
}

fn relative_path(root: &Path, path: &str) -> Result<PathBuf, String> {
    let relative = Path::new(path);
    if relative.as_os_str().is_empty()
        || relative
            .components()
            .any(|part| !matches!(part, Component::Normal(_)))
    {
        return Err(format!(
            "expected a relative path inside the package, got '{path}'"
        ));
    }
    Ok(root.join(relative))
}

fn require_directory(root: &Path, path: &Path, allow_missing: bool) -> Result<(), String> {
    let mut current = root.to_owned();
    for part in path
        .strip_prefix(root)
        .expect("relative content path")
        .components()
    {
        current.push(part);
        let meta = match fs::symlink_metadata(&current) {
            Ok(meta) => meta,
            Err(err) if allow_missing && err.kind() == std::io::ErrorKind::NotFound => {
                return Ok(())
            }
            Err(err) => return Err(format!("{}: {err}", current.display())),
        };
        if !meta.is_dir() || meta.file_type().is_symlink() {
            return Err(format!(
                "web content/output path must be a real directory: {}",
                current.display()
            ));
        }
    }
    Ok(())
}

fn collect_markdown(directory: &Path, paths: &mut Vec<PathBuf>) -> Result<(), String> {
    let mut entries = fs::read_dir(directory)
        .map_err(|err| format!("{}: {err}", directory.display()))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|err| err.to_string())?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        let ty = entry
            .file_type()
            .map_err(|err| format!("{}: {err}", path.display()))?;
        if ty.is_symlink() || (!ty.is_dir() && !ty.is_file()) {
            return Err(format!(
                "content must contain only real files and directories: {}",
                path.display()
            ));
        }
        if ty.is_dir() {
            collect_markdown(&path, paths)?;
        } else if path.extension().is_some_and(|ext| ext == "md") {
            paths.push(path);
        }
    }
    Ok(())
}

fn read_entry(path: &Path, source: String) -> Result<Entry, String> {
    let error = |reason: &str| format!("{source}: {reason}");
    let text = fs::read_to_string(path)
        .map_err(|err| error(&err.to_string()))?
        .replace("\r\n", "\n");
    let rest = text
        .strip_prefix("+++\n")
        .ok_or_else(|| error("expected TOML front matter delimited by +++ lines"))?;
    let mut offset = 0;
    let mut closing = None;
    for line in rest.split_inclusive('\n') {
        if line.strip_suffix('\n').unwrap_or(line) == "+++" {
            closing = Some((offset, offset + line.len()));
            break;
        }
        offset += line.len();
    }
    let (end, body_start) =
        closing.ok_or_else(|| error("missing closing +++ front matter delimiter"))?;
    let meta: FrontMatter = toml::from_str(&rest[..end])
        .map_err(|err| error(&format!("invalid front matter: {err}")))?;
    let body = rest[body_start..].to_owned();
    if meta.slug.is_empty()
        || meta.slug.contains('/')
        || crate::web::static_build::artifact_path(&format!("/{}", meta.slug)).is_err()
    {
        return Err(error("slug must be one portable nonempty URL segment"));
    }
    if meta.title.trim().is_empty() {
        return Err(error("title must not be empty"));
    }
    let mut tags = BTreeSet::new();
    if meta
        .tags
        .iter()
        .any(|tag| tag.trim().is_empty() || tag.trim() != tag || !tags.insert(tag))
    {
        return Err(error("tags must be nonempty, trimmed, and unique"));
    }
    if [&meta.slug, &meta.title, &meta.summary, &body, &source]
        .into_iter()
        .chain(meta.tags.iter())
        .any(|s| s.contains('\0'))
    {
        return Err(error("content strings must not contain NUL"));
    }
    Ok(Entry { meta, body, source })
}

/// Serialize strings for the Nulang lexer (not JSON). No metadata value or
/// Markdown body can inject executable Nulang source through a string literal.
fn quote(s: &str) -> String {
    let mut quoted = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\r' => quoted.push_str("\\r"),
            '\t' => quoted.push_str("\\t"),
            c if c.is_control() => write!(quoted, "\\u{{{:x}}}", c as u32).unwrap(),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}
